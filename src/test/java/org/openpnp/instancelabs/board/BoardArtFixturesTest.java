package org.openpnp.instancelabs.board;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.io.File;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.Collections;
import java.util.LinkedHashMap;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.TreeSet;

import org.junit.jupiter.api.Test;
import org.openpnp.instancelabs.kicad.ImportProposal;
import org.openpnp.model.Board;
import org.openpnp.model.Configuration;

import com.google.gson.GsonBuilder;

/**
 * The board drawings of the browser harness (design §6.3, §6.6): the KiCad art of ftp, mobo and nano and the fallback
 * art of ftp.board.xml (a board without a KiCad source), as {@code src/test/web/fixtures/art/<id>.json}, with
 * {@code board-map-generated.json} beside them (board file name → art id, the format of devproxy.py --fixtures).
 * With {@code -Dil.writeWebFixtures=true} the files are written; otherwise the committed files must equal a fresh
 * build, so a change to the art shows up here first.
 */
public class BoardArtFixturesTest {
    static final File DIR = new File(System.getProperty("user.dir"), "src/test/web/fixtures/art");
    static final String MAP = "board-map-generated.json";
    /** The import time written into the fixtures (fixed, so the bytes and ids are too). */
    static final long AT_MS = 1793000000000L;
    static final String REGENERATE = "regenerate with: env -u DISPLAY -u WAYLAND_DISPLAY mvn -B -o -T1 "
            + "-Dil.writeWebFixtures=true -Dtest=BoardArtFixturesTest test";

    @Test
    public void webFixtures() throws Exception {
        Map<String, byte[]> boards = new LinkedHashMap<>(); // board file name → art bytes
        boards.put("ftp.board.xml", kicad(ArtFixtures.FTP, "ftp"));
        boards.put("ftp-fallback.board.xml", fallback());
        boards.put("mobo.board.xml", kicad(ArtFixtures.MOBO, "mobo"));
        boards.put("nano.board.xml", kicad(ArtFixtures.NANO, "nano"));

        Map<String, Object> map = new LinkedHashMap<>();
        map.put("_note", "Generated by BoardArtFixturesTest from src/test/resources/kicad (sources and licences: "
                + "src/test/resources/kicad/LICENSE.txt); do not edit, " + REGENERATE + ". Board file name -> art "
                + "id (<id>.json in this directory), as devproxy.py --fixtures reads board-map.json. ftp.board.xml: "
                + "the KiCad drawing of ftp.kicad_pcb (what an attach gives the bench's board file); "
                + "ftp-fallback.board.xml: the fallback drawing of ftp.board.xml, a board without a KiCad source "
                + "(BOARD_IMPORT_DESIGN.md §4.3); mobo and nano: named as an import saves them.");
        Map<String, byte[]> files = new LinkedHashMap<>();
        for (Map.Entry<String, byte[]> e : boards.entrySet()) {
            String id = BoardArt.idOf(e.getValue());
            map.put(e.getKey(), id);
            files.put(id + ".json", e.getValue());
        }
        files.put(MAP, (new GsonBuilder().setPrettyPrinting().disableHtmlEscaping().create().toJson(map) + "\n")
                .getBytes(StandardCharsets.UTF_8));

        if (Boolean.getBoolean("il.writeWebFixtures")) {
            Files.createDirectories(DIR.toPath());
            for (File f : listed()) {
                if (!files.containsKey(f.getName())) {
                    Files.delete(f.toPath());
                }
            }
            for (Map.Entry<String, byte[]> e : files.entrySet()) {
                Files.write(new File(DIR, e.getKey()).toPath(), e.getValue());
            }
            System.out.println("BoardArtFixturesTest: wrote " + files.keySet() + " to " + DIR);
        }
        Set<String> present = new TreeSet<>();
        for (File f : listed()) {
            present.add(f.getName());
        }
        assertEquals(new TreeSet<>(files.keySet()), present, "the files in " + DIR + "; " + REGENERATE);
        for (Map.Entry<String, byte[]> e : files.entrySet()) {
            byte[] committed = Files.readAllBytes(new File(DIR, e.getKey()).toPath());
            assertTrue(Arrays.equals(e.getValue(), committed), e.getKey() + " differs from a fresh build; "
                    + REGENERATE);
        }
        for (Map.Entry<String, byte[]> e : boards.entrySet()) {
            BoardArt a = BoardArt.parse(e.getValue());
            assertEquals(e.getValue().length, a.stats.bytes, e.getKey());
            assertTrue(e.getValue().length <= BoardArtBuilder.TARGET_BYTES, e.getKey());
            // the designs' marks are reserved (src/test/resources/kicad/LICENSE.txt): no drawing names them
            String s = new String(e.getValue(), StandardCharsets.UTF_8).toLowerCase(java.util.Locale.ROOT);
            assertFalse(s.contains("opulo") || s.contains("lumenpnp"), e.getKey());
        }
        assertTrue(new File(DIR, "LICENSE.txt").isFile(), "the drawings' licences");
    }

    /** The JSON files of the directory (the art and the map). */
    static List<File> listed() {
        File[] l = DIR.listFiles((d, n) -> n.endsWith(".json"));
        List<File> files = l == null ? new ArrayList<>() : new ArrayList<>(Arrays.asList(l));
        Collections.sort(files);
        return files;
    }

    /** A fixture's KiCad art with the source and import blocks an import named slug would write. */
    static byte[] kicad(String fixture, String slug) throws Exception {
        ArtFixtures.Drawn d = ArtFixtures.draw(fixture);
        BoardArt art = d.art();
        ImportProposal p = d.proposal;
        art.source.name = fixture.replace(".gz", "");
        art.source.bytes = (long) d.bytes.length;
        art.source.sha256 = BoardArt.sha256Hex(d.bytes);
        BoardArt.Import imp = BoardArt.Import.from(p, d.result.warnings);
        imp.how = "import";
        imp.name = slug;
        imp.slug = slug;
        imp.atMs = AT_MS;
        imp.boardDigest = BoardArtIndex.digest(p);
        Set<String> parts = new LinkedHashSet<>();
        for (ImportProposal.PackageP k : p.packages) {
            imp.packages.add(new BoardArt.IdState(packageId(k), "new"));
        }
        for (ImportProposal.PlacementP x : p.placements) {
            String pkg = packageId(p.packages.get(x.packageIndex));
            parts.add(x.value.isEmpty() ? pkg : pkg + "-" + x.value);
        }
        for (String part : parts) {
            imp.parts.add(new BoardArt.IdState(part, "new"));
        }
        art.imported = imp;
        art.measure();
        return art.toBytes();
    }

    /** In a fresh configuration (no packages of its own) every package is new: variant n is baseId~n. */
    static String packageId(ImportProposal.PackageP k) {
        return k.variant == 1 ? k.baseId : k.baseId + "~" + k.variant;
    }

    /** The fallback art of the bench's ftp.board.xml with the seeded pad types; its file named without a path. */
    static byte[] fallback() throws Exception {
        File dir = Files.createTempDirectory("board-art-fixtures").toFile();
        Configuration.initialize(dir);
        Configuration.get().load();
        Board b = ArtFixtures.ftpBoardXml(dir);
        BoardArt art = BoardArtFallback.build(b, ArtFixtures.seedResolver());
        art.source.boardFile = "ftp.board.xml";
        art.measure();
        return art.toBytes();
    }
}
